/**
 * Bakes every theme's chrome palette into `lib/theme/palettes.ts`.
 *
 * Run with `npm run palettes`, and re-run whenever `lib/theme/derive.ts` or the
 * token order in `lib/theme/tokens.ts` changes. `lib/theme/palettes.test.ts`
 * fails if the committed table and the current derivation disagree, so
 * forgetting is caught rather than shipped.
 *
 * ## Why this is a build step rather than a runtime one
 *
 * The derivation needs the theme's JSON, and the theme JSONs are seventy-five
 * lazily-imported chunks. The review page and the options page could afford to
 * await one. The content script cannot: it runs on every github.com page, it
 * has to paint the card in the colours the reviewer chose on the *first* frame
 * rather than after a dynamic import resolves, and a content script's dynamic
 * imports need the chunks declared as web-accessible resources, which would
 * make seventy-five theme files readable by every page on github.com.
 *
 * A table sidesteps all of that. It is about twenty kilobytes of hex, it parses
 * in microseconds, it is identical on all three surfaces, and it cannot go
 * stale against a theme the way a cache in `storage.local` could.
 *
 * ## Why Vite loads the module
 *
 * Node 24 strips TypeScript types on its own, but its ESM resolver still wants
 * explicit file extensions on relative imports, and this repository writes
 * them the way a bundler expects. Rather than change every import in `lib/` to
 * suit one script, the script borrows the bundler that is already a dependency.
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createServer } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'lib', 'theme', 'palettes.ts');

const BANNER = `/**
 * Every theme's chrome palette, derived at build time.
 *
 * **Generated by \`npm run palettes\`. Do not edit.** The derivation, and the
 * reasoning behind every value in it, is \`lib/theme/derive.ts\`;
 * \`lib/theme/palettes.test.ts\` re-derives a sample and fails if this file has
 * fallen behind it.
 *
 * Values are packed positionally — one comma-joined run of opaque six-digit hex
 * per theme, in \`CHROME_TOKENS\` order — rather than as objects. Seventy-five
 * copies of forty property names is the only part of this feature large enough
 * to be worth avoiding in a script that loads on every github.com page.
 *
 * Pure data, so it is safe in \`lib/\`: no DOM, no \`chrome.*\`, no network.
 */

import { type ChromeTheme, decodePalette } from './tokens';
`;

/** The generated file's body: the packed table plus its two readers. */
function render(rows) {
  const lines = rows
    .map(({ id, scheme, packed }) => `  '${id}': '${scheme[0]}${packed}',`)
    .join('\n');

  return `${BANNER}
/**
 * Theme id to a packed palette, prefixed with the theme's own colour scheme —
 * \`l\` or \`d\`, one character, because the scheme has to travel with the values
 * and a boolean field per row would cost more than the rest of the table.
 */
const PACKED: Record<string, string> = {
${lines}
};

/** Every theme this table covers. Its length is asserted by the test. */
export const THEMED_COUNT = ${rows.length};

/**
 * The chrome for this theme, or null for a theme this build cannot draw.
 *
 * Null is also the honest answer for the empty string, which is not a theme id
 * — it is \`THEME_FOLLOWS_PAGE\`, and it means the Primer defaults in
 * \`ui/tokens.css\` are left alone.
 */
export function chromeTheme(id: string): ChromeTheme | null {
  const packed = PACKED[id];
  if (packed === undefined) return null;
  return {
    scheme: packed[0] === 'd' ? 'dark' : 'light',
    palette: decodePalette(packed.slice(1)),
  };
}
`;
}

const server = await createServer({
  configFile: false,
  root,
  appType: 'custom',
  logLevel: 'warn',
  server: { middlewareMode: true },
  optimizeDeps: { noDiscovery: true },
});

try {
  const { DIFF_THEMES } = await server.ssrLoadModule('/lib/compare/themes.ts');
  const { deriveChromeTheme, packPalette } = await server.ssrLoadModule('/lib/theme/derive.ts');
  const { themes } = await server.ssrLoadModule('@pierre/theming/themes');

  const descriptors = new Map(themes.getThemes().map((entry) => [entry.name, entry]));
  const rows = [];

  for (const { id } of DIFF_THEMES) {
    const descriptor = descriptors.get(id);
    // Loud rather than skipped. A theme the options page offers and this table
    // has no row for is a reviewer choosing a theme and getting Primer chrome
    // with it, which is the exact bug this feature exists to remove.
    if (descriptor === undefined) {
      throw new Error(`'${id}' is offered by lib/compare/themes.ts but @pierre/theming has no theme by that name`);
    }
    const loaded = await descriptor.load();
    const theme = loaded.default ?? loaded;
    const { scheme, palette } = deriveChromeTheme(theme);
    rows.push({ id, scheme, packed: packPalette(palette) });
  }

  await writeFile(OUT, render(rows), 'utf8');
  console.log(`lib/theme/palettes.ts: ${rows.length} themes`);
} finally {
  await server.close();
}
